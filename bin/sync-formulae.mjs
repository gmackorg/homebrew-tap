#!/usr/bin/env node
/**
 * Regenerate every formula in this tap from the latest GitHub release of the project that
 * produces it.
 *
 * The tap pulls rather than each project pushing. Pushing needs a credential that can write to
 * *this* repository from *another* one — a PAT or a deploy key — held by every project, rotated
 * in every project, and able to do more than the one thing it is for. Pulling needs nothing: a
 * workflow in this repository already has write access to this repository, and a public release
 * is readable without auth. One mechanism, no shared secret, and a new CLI joins by adding four
 * lines to tap.json.
 *
 * Checksums are never computed here. They are read from the `.sha256` files the release
 * published, which were computed on the machine that built the binary — recomputing them from a
 * download would only prove the download matched itself.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const TARGETS = {
  "aarch64-apple-darwin": { os: "macos", cpu: "arm" },
  "x86_64-apple-darwin": { os: "macos", cpu: "intel" },
  "aarch64-unknown-linux-gnu": { os: "linux", cpu: "arm" },
  "x86_64-unknown-linux-gnu": { os: "linux", cpu: "intel" },
};

const token = process.env["GITHUB_TOKEN"] ?? "";
const api = async (path) => {
  const res = await fetch(`https://api.github.com${path}`, {
    headers: { accept: "application/vnd.github+json", "user-agent": "gmackorg-tap-sync", ...(token ? { authorization: `Bearer ${token}` } : {}) },
  });
  if (!res.ok) throw new Error(`GET ${path} -> ${res.status} ${await res.text().catch(() => "")}`.slice(0, 300));
  return res.json();
};

const className = (name) => name.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");

function render({ name, repo, desc, license, version, assets }) {
  const url = (a) => `https://github.com/${repo}/releases/download/v${version}/${a.file}`;
  const block = (os, cpu) => {
    const a = assets.find((x) => x.os === os && x.cpu === cpu);
    return a ? `      url "${url(a)}"\n      sha256 "${a.sha256}"` : null;
  };
  const platform = (os) => {
    const arm = block(os, "arm");
    const intel = block(os, "intel");
    if (!arm && !intel) return "";
    const parts = [];
    if (arm) parts.push(`    if Hardware::CPU.arm?\n${arm}`);
    if (intel) parts.push(`    ${arm ? "els" : ""}if Hardware::CPU.intel?\n${intel}`);
    return `  on_${os} do\n${parts.join("\n")}\n    end\n  end\n\n`;
  };
  return `# Generated by bin/sync-formulae.mjs from the ${repo} v${version} release. Do not edit by hand.
class ${className(name)} < Formula
  desc "${desc}"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "${license}"

${platform("macos")}${platform("linux")}  def install
    bin.install "${name}"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${name} --version")
  end
end
`;
}

const config = JSON.parse(readFileSync("tap.json", "utf8"));
mkdirSync("Formula", { recursive: true });
let changed = 0;
const problems = [];

for (const f of config.formulae) {
  let release;
  try {
    release = await api(`/repos/${f.repo}/releases/latest`);
  } catch (e) {
    // A project with no release yet is normal, not a failure of this tap.
    console.error(`${f.name}: no readable release on ${f.repo} (${String(e.message).slice(0, 120)})`);
    continue;
  }
  const version = String(release.tag_name ?? "").replace(/^v/, "");
  if (!/^\d+\.\d+\.\d+/.test(version)) {
    problems.push(`${f.name}: latest release tag "${release.tag_name}" is not v<semver>`);
    continue;
  }

  const assets = [];
  for (const [target, spec] of Object.entries(TARGETS)) {
    const tar = `${f.name}-${version}-${target}.tar.gz`;
    const sum = release.assets?.find((a) => a.name === `${tar}.sha256`);
    if (!sum) continue; // platform not built for this release; omitted rather than guessed
    const res = await fetch(sum.browser_download_url, { headers: { "user-agent": "gmackorg-tap-sync" } });
    if (!res.ok) {
      problems.push(`${f.name}: could not read ${sum.name} (${res.status})`);
      continue;
    }
    const sha256 = (await res.text()).trim().split(/\s+/)[0];
    if (!/^[0-9a-f]{64}$/.test(sha256)) {
      problems.push(`${f.name}: ${sum.name} does not contain a sha256`);
      continue;
    }
    assets.push({ ...spec, file: tar, sha256 });
  }
  if (assets.length === 0) {
    problems.push(`${f.name}: release v${version} published no <name>-<version>-<target>.tar.gz.sha256 assets`);
    continue;
  }

  const path = join("Formula", `${f.name}.rb`);
  const next = render({ ...f, license: f.license ?? "Apache-2.0", version, assets });
  const prev = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (prev === next) {
    console.error(`${f.name}: already at ${version}`);
    continue;
  }
  writeFileSync(path, next);
  console.error(`${f.name}: ${prev ? "updated to" : "added at"} ${version} (${assets.length} platforms)`);
  changed++;
}

for (const p of problems) console.error(`::warning::${p}`);
if (changed) {
  execFileSync("git", ["config", "user.name", "gmackorg-tap"], { stdio: "inherit" });
  execFileSync("git", ["config", "user.email", "tap@users.noreply.github.com"], { stdio: "inherit" });
  execFileSync("git", ["add", "Formula"], { stdio: "inherit" });
  const names = readdirSync("Formula").filter((n) => n.endsWith(".rb")).length;
  execFileSync("git", ["commit", "-m", `Sync ${changed} formula${changed > 1 ? "e" : ""} from upstream releases (${names} total)`], { stdio: "inherit" });
  execFileSync("git", ["push"], { stdio: "inherit" });
  console.error("pushed");
} else {
  console.error("nothing to update");
}
// A warning is not a failure: one project's malformed release must not stop the others syncing.
process.exit(0);
